"""Which fields of SchoolMan are in use, abandoned, rare or never used — from the profiles.

    python3 scripts/filemaker/fields_report.py > docs/schoolman/fields.md

Reads output/filemaker/<Table>.profile.json (written by profile_table.py with a
creation date) and sorts every stored field:

- in use     — filled on rows made since last year;
- abandoned  — filled on older rows, on none since last year;
- rare       — in use, but on fewer than 1% of last year's rows and fewer than 20 of them;
- never      — never filled.

Constants (`_1`, `_2` …) and the audit fields are left out of the lists. Field
names only; no values.
"""
import glob, json, os, re

D = os.path.join(os.path.dirname(__file__), '..', '..', 'output', 'filemaker')
CONST = re.compile(r'^_\d+(_\d+)?$')
AUDIT = re.compile(r'^(DateOfCreation|DateOfChange|DateOfLatestChange|TimeStampOf\w+|Timestamp\w*|TimestampOf\w+|UserName\w*|User|Account_?[Nn]ame|DateCreation|DateChange|Zime\w*)$')


def sort_fields(p):
    rows_recent = p.get('recent_rows') or 0
    groups = {'use': [], 'rare': [], 'abandoned': [], 'never': []}
    for name, f in p['fields'].items():
        if 'error' in f or CONST.match(name) or AUDIT.match(name) or name.startswith('__ID'):
            continue
        if f['filled'] == 0:
            groups['never'].append((name, f))
        elif f.get('recent', 0) == 0:
            groups['abandoned'].append((name, f))
        elif f['recent'] < 20 and f['recent'] < 0.01 * max(rows_recent, 1):
            groups['rare'].append((name, f))
        else:
            groups['use'].append((name, f))
    return groups


def main():
    profiles = []
    for path in sorted(glob.glob(os.path.join(D, '*.profile.json'))):
        p = json.load(open(path))
        if p.get('date_field') and p.get('recent_rows'):
            profiles.append(p)
    since = profiles[0]['recent_since'] if profiles else '?'
    print('# Which SchoolMan fields are in use\n')
    print('Generated by `scripts/filemaker/fields_report.py` from the live profiles in `output/filemaker/`'
          f' (read-only, counts only). "In use" means filled on a row created since {since}; "abandoned" means'
          ' filled on older rows only, with the year it was last filled; "rare" means filled on fewer than 1%'
          f' and fewer than 20 of the rows created since {since}. Constants and audit fields are left out.'
          ' Tables whose rows are generated ahead are not here — their creation dates mislead. `*` marks a field'
          ' FileMaker fills in itself (auto-entered) — sometimes a real value with a default, often a copy.\n')
    print('| Table | Rows | Since ' + since + ' | Fields | In use | Rare | Abandoned | Never |')
    print('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
    sorted_profiles = sorted(profiles, key=lambda p: -p['rows'])
    for p in sorted_profiles:
        g = sort_fields(p)
        total = sum(len(v) for v in g.values())
        print(f"| `{p['table']}` | {p['rows']:,} | {p['recent_rows']:,} | {total} | {len(g['use'])} | {len(g['rare'])} | {len(g['abandoned'])} | {len(g['never'])} |")
    for p in sorted_profiles:
        g = sort_fields(p)
        print(f"\n## {p['table']}\n")
        print('**In use** — ' + (', '.join(f"`{n}`{'*' if f.get('derived') else ''}" for n, f in sorted(g['use'], key=lambda x: -x[1]['recent'])) or '—'))
        if g['rare']:
            print('\n**Rare** — ' + ', '.join(f"`{n}` ({f['recent']})" for n, f in g['rare']))
        if g['abandoned']:
            print('\n**Abandoned** — ' + ', '.join(f"`{n}` ({f['filled']}, last {f.get('last_year') or '?'})" for n, f in sorted(g['abandoned'], key=lambda x: x[1].get('last_year') or '')))
        if g['never']:
            print('\n**Never used** — ' + ', '.join(f'`{n}`' for n, _ in g['never']))


if __name__ == '__main__':
    main()
