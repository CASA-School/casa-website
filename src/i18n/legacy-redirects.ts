/** The workspace host serves /admin only; an old public URL means nothing there. */
const ADMIN_HOST = 'admin[.-].*';

/** Characters Next reads as pattern syntax in a redirect `source`. */
const escapeSource = (path: string) => path.replace(/[\\():*+?{}!]/g, (c) => `\\${c}`);

/** A `has` value is matched as an anchored regular expression. */
const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * The map as Next redirect rules: permanent (308), and never on the admin host.
 *
 * Some old news links were HTML-escaped, so search engines indexed
 * `?…&amp;tx_news_pi1[news]=4` and the parameter arrives named
 * `amp;tx_news_pi1[news]`. Each news rule is emitted for both spellings.
 */
export function legacyRedirectRules() {
  return LEGACY_REDIRECTS.flatMap(([from, to]) => {
    const [path, query] = from.split('?');
    const rule = {
      source: escapeSource(path),
      destination: to,
      permanent: true as const,
      missing: [{ type: 'host' as const, value: ADMIN_HOST }],
    };
    if (!query) {
      return [rule];
    }
    const [[key, value]] = [...new URLSearchParams(query)];
    const keys = key.startsWith('tx_news_pi1') ? [key, `amp;${key}`] : [key];
    return keys.map((name) => ({ ...rule, has: [{ type: 'query' as const, key: name, value: escapeRegExp(value) }] }));
  });
}
