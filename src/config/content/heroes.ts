import { proofMetricsByLocale } from '@/config/content/proof-metrics';
import { socialProofByLocale } from '@/config/content/social-proof';
import { resolveHeroMedia } from '@/config/content/media-library';
import type {
  ContentLocale,
  HeroArchetype,
  HeroCta,
  HeroPageKey,
  HeroSpec,
  HeroThemeKey,
  HeroVariant,
} from '@/lib/content/types';

type HeroSeed = {
  pageKey: HeroPageKey;
  variant: HeroVariant;
  archetype: HeroArchetype;
  themeKey: HeroThemeKey;
  eyebrow: string;
  headline: string;
  subheadline: string;
  ctas: HeroCta[];
  chips?: string[];
  visualKey: Parameters<typeof resolveHeroMedia>[0];
  metricCount?: number;
  storyIndex?: number;
};

function pageMetrics(locale: ContentLocale, size = 4) {
  return proofMetricsByLocale[locale].slice(0, size);
}

function pageStory(locale: ContentLocale, index = 0) {
  const item = socialProofByLocale[locale][index] ?? socialProofByLocale[locale][0];

  return {
    quote: item.quote,
    personDisplay: item.personDisplay,
    country: item.country,
    roleLabel: locale === 'de' ? 'Lernstimme' : 'Student voice',
    sourcePlatform: item.sourcePlatform,
    sourceUrl: item.sourceUrl,
    verificationStatus: item.verificationStatus,
  };
}

function toRecord(locale: ContentLocale, seeds: HeroSeed[]): Record<HeroPageKey, HeroSpec> {
  return seeds.reduce<Record<HeroPageKey, HeroSpec>>((acc, seed) => {
    acc[seed.pageKey] = {
      pageKey: seed.pageKey,
      locale,
      variant: seed.variant,
      archetype: seed.archetype,
      themeKey: seed.themeKey,
      eyebrow: seed.eyebrow,
      headline: seed.headline,
      subheadline: seed.subheadline,
      ctas: seed.ctas,
      proofMetrics: pageMetrics(locale, seed.metricCount ?? 4),
      story: pageStory(locale, seed.storyIndex ?? 0),
      chips: seed.chips,
      visual: {
        kind: 'image',
        src: resolveHeroMedia(seed.visualKey),
        alt: seed.headline,
      },
    };

    return acc;
  }, {} as Record<HeroPageKey, HeroSpec>);
}

